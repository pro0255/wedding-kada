export function kresli(
  ctx: CanvasRenderingContext2D,
  sp: Sprite,
  x: number,
  y: number,
  ink: string,
  zlata: string,
  meritko = S,
) {
  const bx = Math.round(x);
  const by = Math.round(y);
  for (let r = 0; r < sp.length; r++) {
    const radek = sp[r];
    for (let c = 0; c < radek.length; c++) {
      const ch = radek[c];
      if (ch === ".") continue;
      ctx.fillStyle = ch === "o" ? zlata : ink;
      ctx.fillRect(bx + c * meritko, by + r * meritko, meritko, meritko);
    }
  }
}

export const sirka = (sp: Sprite) => sp[0].length * S;
export const vyska = (sp: Sprite) => sp.length * S;

